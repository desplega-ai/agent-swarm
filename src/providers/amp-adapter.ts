/**
 * The pinned Amp CLI. Amp ships several releases a day and auto-updates by
 * default; the image installs exactly this version and the per-task settings
 * set `amp.updates.mode: "disabled"`. Bump it deliberately, with a live run.
 */
export const AMP_PACKAGE = "@ampcode/cli@0.0.1791187719-g319a37";

/** MCP server name. Amp exposes its tools as `agent_swarm` / `store_progress` (dashes become underscores). */
const AMP_MCP_SERVER_NAME = "agent-swarm";
/** Key of the per-task plugin mode that carries the swarm system prompt and any model pin. */
const AMP_PLUGIN_MODE_KEY = "agent-swarm";
/** Live test and thread export budgets. A missing key can make Amp wait instead of failing. */
const AMP_LIVE_TEST_TIMEOUT_MS = 5_000;
const AMP_EXPORT_TIMEOUT_MS = 20_000;
const AMP_EXPORT_RETRY_MS = 3_000;
const AMP_EXPORT_RETRIES = 1;
