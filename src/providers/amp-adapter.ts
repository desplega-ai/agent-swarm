/**
 * The per-task plugin: one agent mode that extends a built-in mode, appends the
 * swarm system prompt as `instructions`, and optionally pins a model and an
 * effort. Amp has no system-prompt flag, so this is the supported route (live
 * verified: the instructions reach the model). The values are a JSON literal,
 * never code, so a prompt cannot break out of the string.
 *
 * With a `steeringInbox`, a `tool.result` hook appends every queued steering
 * message to the next tool result, so the model reads it mid-turn. Amp's own
 * `--stream-json-input` queue only starts a message after the whole turn ends,
 * by which time the task has usually finished (live verified both ways).
 */
export function buildAmpPlugin(options: {
  baseMode: AmpMode;
  instructions: string;
  pin?: string;
  reasoningEffort?: string | null;
  steeringInbox?: string;
}): string {
  const config = JSON.stringify({
    baseMode: options.baseMode,
    instructions: options.instructions,
    model: options.pin ?? null,
    reasoningEffort: options.reasoningEffort ?? null,
    steeringInbox: options.steeringInbox ?? null,
  });
  return `// @amp-agent-mode key=${AMP_PLUGIN_MODE_KEY} label=Agent Swarm
// Generated by the agent-swarm worker for one task. Do not edit.
import { readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";

export const description = "Agent Swarm worker mode generated for one task.";

const CONFIG = ${config};

/**
 * Claim each queued message by renaming it (.json -> .taken), so the worker and
 * this hook never both deliver one. A message handed to Amp becomes .read,
 * naming the tool call whose result carries it, and stays until the worker sees
 * the model that received that result answer: a crash before that leaves it for
 * the worker to report as undelivered.
 */
function takeSteering(toolUseID: unknown): string[] {
	if (!CONFIG.steeringInbox) return [];
	let names: string[];
	try {
		names = readdirSync(CONFIG.steeringInbox).filter((name) => name.endsWith(".json")).sort();
	} catch {
		return [];
	}
	const texts: string[] = [];
	for (const name of names) {
		const path = CONFIG.steeringInbox + "/" + name;
		const claimed = path + ".taken";
		try {
			renameSync(path, claimed);
		} catch {
			continue;
		}
		let text: string;
		try {
			text = JSON.parse(readFileSync(claimed, "utf8"));
		} catch {
			// Unreadable: dropped, and the worker reports it undelivered.
			rmSync(claimed, { force: true });
			continue;
		}
		texts.push(text);
		try {
			writeFileSync(claimed, JSON.stringify({ text, toolUseID }));
			renameSync(claimed, path + ".read");
		} catch {
			// The worker treats a claim left as .taken as unconsumed.
		}
	}
	return texts;
}

function withSteering(output: unknown, note: string): unknown {
	if (Array.isArray(output)) return [...output, { type: "text", text: note }];
	if (output === undefined || output === null) return note;
	return (typeof output === "string" ? output : JSON.stringify(output)) + note;
}

export default function (amp: any) {
	amp.on("tool.result", (event: any) => {
		const texts = takeSteering(event.toolUseID);
		if (texts.length === 0) return;
		const note = texts.map((text) => "\\n\\n" + text).join("");
		return {
			status: event.status,
			...(event.error ? { error: event.error } : {}),
			output: withSteering(event.output, note),
		};
	});
	amp.registerAgentMode({
		key: ${JSON.stringify(AMP_PLUGIN_MODE_KEY)},
		label: "Agent Swarm",
		agent: amp.createAgent({
			extends: CONFIG.baseMode,
			...(CONFIG.instructions ? { instructions: CONFIG.instructions } : {}),
			...(CONFIG.model ? { model: CONFIG.model } : {}),
			...(CONFIG.reasoningEffort ? { reasoningEffort: CONFIG.reasoningEffort } : {}),
			display: { label: "Agent Swarm" },
		}).definition,
	});
}
`;
}

