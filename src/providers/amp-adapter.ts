// ─── Live test ───────────────────────────────────────────────────────────────

export interface AmpLiveTestResult {
  ok: boolean;
  error?: string;
}

/**
 * `amp usage` reads the credit balance and runs no inference. It exits 1 with
 * "Invalid or missing API key" for a bad key. The output of a good key names
 * the account holder, so it is never returned.
 */
export async function liveTestAmpCredentials(
  env: Record<string, string | undefined>,
  timeoutMs: number = AMP_LIVE_TEST_TIMEOUT_MS,
): Promise<AmpLiveTestResult> {
  const binary = resolveAmpBinary(env);
  if (!binary) {
    return {
      ok: false,
      error: `amp CLI not found. Install ${AMP_PACKAGE} during image provisioning or set AMP_BINARY to a trusted executable.`,
    };
  }
  // The key may exist only in this env, where the scrubber cannot see it, and
  // `amp usage` can echo it in an error.
  const apiKey = env.AMP_API_KEY?.trim();
  if (apiKey) registerVolatileSecret(apiKey, "AMP_API_KEY");
  // A clean config dir keeps a stored `amp login` from masking a bad AMP_API_KEY.
  const configHome = await mkdtemp(join(tmpdir(), "swarm-amp-live-"));
  try {
    const proc = registerProcessGroup(
      Bun.spawn([binary, "usage"], {
        env: {
          ...(env as Record<string, string>),
          XDG_CONFIG_HOME: configHome,
          AMP_SETTINGS_FILE: join(configHome, "amp", "settings.json"),
        },
        stdin: "ignore",
        stdout: "pipe",
        stderr: "pipe",
        detached: detachedProcessGroup,
      }),
    );
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      void terminateProcessGroup(proc.pid);
    }, timeoutMs);
    try {
      const [exitCode, stdout, stderr] = await Promise.all([
        proc.exited,
        new Response(proc.stdout).text(),
        new Response(proc.stderr).text(),
      ]);
      if (timedOut) return { ok: false, error: `amp usage timed out after ${timeoutMs}ms` };
      if (exitCode === 0) return { ok: true };
      const line =
        (stderr.trim() || stdout.trim()).split("\n")[0]?.replace(/^Error:\s*/, "") ||
        `amp usage exited ${exitCode}`;
      return { ok: false, error: scrubSecrets(line).slice(0, 300) };
    } finally {
      clearTimeout(timer);
    }
  } finally {
    await rm(configHome, { recursive: true, force: true });
  }
}

// ─── Thread cost (what Amp billed) ───────────────────────────────────────────

/**
 * The dollars Amp recorded for a thread, from `amp threads usage <id> --details`
 * (markdown; the CLI has no JSON form). It covers the whole thread, subagent
 * threads included, at what Amp billed, so it is the harness cost, like
 * Devin's ACUs. Returns undefined when usage is not available yet, or when any
 * request was routed through a linked provider (a ChatGPT subscription records
 * $0 in Amp and bills outside it): the API then prices the tokens instead.
 */
export function parseAmpThreadCost(text: string): number | undefined {
  const cost = /^Cost: \$([\d,]+(?:\.\d+)?)\s*$/m.exec(text);
  if (!cost?.[1]) return undefined;
  const routing = text.split(/^## Model Routing\s*$/m)[1];
  if (routing === undefined) return undefined;
  const rows = routing
    .split(/^## /m)[0]
    ?.split("\n")
    .map((line) => line.trim())
    .filter((line) => line.startsWith("|") && !/^\|\s*(Model ID|-)/.test(line));
  for (const row of rows ?? []) {
    if (row.split("|")[3]?.trim() !== "Via Amp") return undefined;
  }
  const usd = Number(cost[1].replaceAll(",", ""));
  return Number.isFinite(usd) ? usd : undefined;
}

// ─── Thread export (model, tokens, context window) ───────────────────────────

export interface AmpThreadUsage {
  models: CostModelUsage[];
  /** Model of the most tokens: the one the session mostly ran on. */
  primaryModel?: string;
  /** Amp's effective input limit for that model, from the last request. */
  contextWindow?: number;
  contextUsedTokens?: number;
  lastOutputTokens?: number;
}

function count(value: unknown): number {
  return typeof value === "number" && Number.isFinite(value) && value > 0 ? value : 0;
}

/**
 * The stream names no model, so the model and the per-request usage come from
 * `amp threads export <id>`. Per model, cache-creation tokens stay cache writes
 * for Anthropic and become input for everyone else: Amp reports uncached prompt
 * tokens as `cache_creation_input_tokens` on every vendor, and the pricing
 * table charges a missing cache-write rate as $0.
 *
 * Subagent threads (Task, oracle, finder) are separate Amp threads and are not
 * in the export, so their tokens are not counted.
 */
export function parseAmpThreadUsage(thread: unknown): AmpThreadUsage | undefined {
  const messages = (thread as { messages?: unknown })?.messages;
  if (!Array.isArray(messages)) return undefined;
  const byModel = new Map<string, CostModelUsage>();
  let last: Record<string, unknown> | undefined;
  for (const message of messages) {
    const usage = (message as { role?: string; usage?: Record<string, unknown> } | null)?.usage;
    if ((message as { role?: string } | null)?.role !== "assistant" || !usage) continue;
    const model = typeof usage.model === "string" && usage.model ? usage.model : undefined;
    if (!model) continue;
    const entry = byModel.get(model) ?? {
      model,
      inputTokens: 0,
      outputTokens: 0,
      cacheReadTokens: 0,
      cacheWriteTokens: 0,
    };
    const cacheCreation = count(usage.cacheCreationInputTokens);
    entry.inputTokens += count(usage.inputTokens);
    entry.outputTokens += count(usage.outputTokens);
    entry.cacheReadTokens += count(usage.cacheReadInputTokens);
    if (ampBillsCacheWrites(model)) entry.cacheWriteTokens += cacheCreation;
    else entry.inputTokens += cacheCreation;
    byModel.set(model, entry);
    last = usage;
  }
  if (byModel.size === 0) return undefined;
  const models = [...byModel.values()];
  const total = (m: CostModelUsage) =>
    m.inputTokens + m.outputTokens + m.cacheReadTokens + m.cacheWriteTokens;
  const primaryModel = [...models].sort((a, b) => total(b) - total(a))[0]?.model;
  const window = count(last?.maxInputTokens);
  return {
    models,
    primaryModel,
    contextWindow: window || undefined,
    contextUsedTokens: last ? count(last.totalInputTokens) + count(last.outputTokens) : undefined,
    lastOutputTokens: last ? count(last.outputTokens) : undefined,
  };
}

