import { describe, expect, test } from "bun:test";
import {
  type CopyMigrationsInput,
  checkCopyMigrations,
  rowChanges,
  splitStatements,
} from "../../scripts/storage-checks/check-copy-migrations";

const changes = (sql: string) =>
  splitStatements(sql)
    .flatMap(rowChanges)
    .map((change) => `${change.verb}:${change.table}${change.plainSeed ? ":seed" : ""}`);

describe("splitStatements", () => {
  test("splits at top-level semicolons only", () => {
    const statements = splitStatements(`
      -- UPDATE in a comment; not a statement
      /* DELETE FROM a; /* nested; */ still a comment; */
      CREATE TABLE "odd;name" (id text DEFAULT 'a;b', note text DEFAULT E'it\\'s; one');
      CREATE FUNCTION f() RETURNS trigger LANGUAGE plpgsql AS $body$
      BEGIN UPDATE t SET a = 1; RETURN NEW; END $body$;
      INSERT INTO t (a) VALUES ('x; UPDATE t SET a = 2');
    `);
    expect(statements).toHaveLength(3);
    expect(statements[0]).toStartWith('CREATE TABLE "odd;name"');
    expect(statements[1]).toBe("CREATE FUNCTION f() RETURNS trigger LANGUAGE plpgsql AS $$$$");
    expect(statements[2]).toBe("INSERT INTO t (a) VALUES ('')");
  });

  test("keeps a SQL-standard function body in its CREATE statement", () => {
    const statements = splitStatements(`
      CREATE FUNCTION f() RETURNS void LANGUAGE sql BEGIN ATOMIC
        UPDATE t SET a = 1; DELETE FROM t WHERE a = 2;
      END;
      UPDATE t SET a = 3;
    `);
    expect(statements).toHaveLength(2);
    expect(statements.flatMap(rowChanges).map((c) => c.verb)).toEqual(["update"]);
  });
});

describe("rowChanges", () => {
  test("schema statements change no row", () => {
    expect(
      changes(`
        CREATE EXTENSION IF NOT EXISTS vector;
        CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY, a text);
        CREATE INDEX t_a ON t (a);
        ALTER TABLE t ADD COLUMN b text NOT NULL DEFAULT 'x';
        ALTER TABLE t ADD FOREIGN KEY (a) REFERENCES u (id) ON DELETE CASCADE;
        CREATE TRIGGER tr AFTER INSERT OR UPDATE OR DELETE ON t FOR EACH ROW EXECUTE FUNCTION f();
        CREATE VIEW v AS SELECT * FROM t;
        COMMENT ON TABLE t IS 'INSERT INTO t';
        DROP INDEX t_a;
        SELECT setval(pg_get_serial_sequence('"t"', 'id'), (SELECT max("id") FROM "t"));
        COPY t TO STDOUT;
      `),
    ).toEqual([]);
  });

  test("names the verb and the table of each write", () => {
    expect(
      changes(`
        INSERT INTO "channels" ("id", "name") VALUES ('1', 'general');
        INSERT INTO t DEFAULT VALUES;
        INSERT INTO t (a) OVERRIDING SYSTEM VALUE VALUES (1) ON CONFLICT (a) DO UPDATE SET a = 2;
        INSERT INTO t (a) SELECT a FROM u;
        INSERT INTO public.t (a) VALUES (1);
        INSERT INTO "public"."Mixed" (a) VALUES (1);
        INSERT INTO Mixed (a) VALUES (1);
        UPDATE metrics SET definition = '{}' WHERE slug = 'x';
        UPDATE ONLY "agent_tasks" SET "status" = 'failed';
        DELETE FROM t WHERE a IS NULL;
        MERGE INTO t USING u ON t.a = u.a WHEN MATCHED THEN DELETE;
        TRUNCATE TABLE t;
        COPY t (a) FROM STDIN;
        ALTER TABLE t ALTER COLUMN a TYPE bigint USING (a::bigint * 1000);
      `),
    ).toEqual([
      "insert:channels:seed",
      "insert:t:seed",
      "insert:t:seed",
      "insert:t",
      "insert:t:seed",
      "insert:Mixed:seed",
      "insert:mixed:seed",
      "update:metrics",
      "update:agent_tasks",
      "delete:t",
      "merge:t",
      "truncate:t",
      "copy:t",
      "alter-using:t",
    ]);
  });

  test("a WITH statement counts for each table it writes", () => {
    expect(
      changes(`
        WITH moved AS (DELETE FROM a WHERE old RETURNING *)
          INSERT INTO b SELECT * FROM moved ON CONFLICT (id) DO UPDATE SET x = 1;
        WITH locked AS (SELECT id FROM a FOR UPDATE) UPDATE c SET x = 1 FROM locked;
        WITH n AS (SELECT 1) SELECT refresh_everything() FROM n;
      `),
    ).toEqual(["insert:b", "delete:a", "update:c", "select:-"]);
  });

  test("a statement the check cannot read is a row change", () => {
    expect(
      changes(`
        DO $$ BEGIN UPDATE t SET a = 1; END $$;
        CALL backfill();
        SELECT backfill();
        REFRESH MATERIALIZED VIEW m;
      `),
    ).toEqual(["do:-", "call:-", "select:-", "refresh:-"]);
  });
});

describe("checkCopyMigrations", () => {
  const SEED = `CREATE TABLE "seeded" (id text);\nINSERT INTO "seeded" (id) VALUES ('a');`;
  const input = (over: Partial<CopyMigrationsInput>): CopyMigrationsInput => ({
    migrations: [{ name: "001_base", sql: SEED }],
    reapply: [],
    seededTables: new Set(["seeded"]),
    seedExceptions: new Set(),
    allowlist: new Map(),
    ...over,
  });
  const REWRITE = { name: "002_port", sql: `UPDATE "seeded" SET id = 'postgres form';` };

  test("a plain seed that db-copy replaces passes", () => {
    expect(checkCopyMigrations(input({}))).toEqual({
      problems: [],
      seeds: 1,
      rerun: 0,
      explained: 0,
    });
  });

  test("a row rewrite fails until it is rerun after the copy or explained", () => {
    const migrations = [{ name: "001_base", sql: SEED }, REWRITE];
    const failed = checkCopyMigrations(input({ migrations }));
    expect(failed.problems).toHaveLength(1);
    expect(failed.problems[0]).toStartWith("002_port:update:seeded: db-copy undoes this statement");

    expect(checkCopyMigrations(input({ migrations, reapply: ["002_port"] }))).toMatchObject({
      problems: [],
      rerun: 1,
    });
    expect(
      checkCopyMigrations(
        input({
          migrations,
          allowlist: new Map([["002_port:update:seeded", "the SQLite file makes the same change"]]),
        }),
      ),
    ).toMatchObject({ problems: [], explained: 1 });
  });

  test("a seed that db-copy does not find fails", () => {
    const result = checkCopyMigrations(input({ seededTables: new Set() }));
    expect(result.problems).toHaveLength(1);
    expect(result.problems[0]).toStartWith(
      "001_base:insert:seeded: db-copy does not find this seed",
    );
  });

  test("a seed in a table where the chains may differ needs a reason", () => {
    const result = checkCopyMigrations(input({ seedExceptions: new Set(["seeded"]) }));
    expect(result.problems).toHaveLength(1);
    expect(result.problems[0]).toContain("schema-parity-allowlist.txt has rows:seeded");
    expect(
      checkCopyMigrations(
        input({
          seedExceptions: new Set(["seeded"]),
          allowlist: new Map([["001_base:insert:seeded", "the same row on both engines"]]),
        }),
      ).problems,
    ).toEqual([]);
  });

  test("a stale allowlist entry and an unknown after-copy name fail", () => {
    const result = checkCopyMigrations(
      input({
        reapply: ["009_gone"],
        allowlist: new Map([["001_base:update:seeded", "no such statement"]]),
      }),
    );
    expect(result.problems).toEqual([
      "after-copy.json lists 009_gone, which is not a migration in src/be/migrations/postgres",
      "copy-migrations-allowlist.txt: 001_base:update:seeded matches no statement. Remove the entry.",
    ]);
  });
});
