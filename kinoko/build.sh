#!/bin/bash
# Builds what both workloads need, for linux/amd64 (the Kinoko guest):
#   1. kinoko-swarm:<tag>            the API image under test plus the client scripts
#   2. kinoko-swarm-postgres:pg18    PostgreSQL 18 with pgvector, small
#   3. postgres/model.lua and sqlite/model.lua, from model/common.lua and the
#      variant's faults file
#
# Usage: kinoko/build.sh [--models-only]
#   SWARM_IMAGE=ghcr.io/desplega-ai/agent-swarm:sha-<7 chars>   the API image to test
#   (default: the image the compose files name). To test a branch, build it first
#   (`docker build -f Dockerfile --platform linux/amd64 -t my-api .`), then pass
#   SWARM_IMAGE=my-api.
set -euo pipefail
cd "$(dirname "$0")"

SWARM_TAG=sha-7dce4fa
SWARM_IMAGE=${SWARM_IMAGE:-ghcr.io/desplega-ai/agent-swarm:$SWARM_TAG}

for variant in postgres sqlite; do
  {
    echo "-- GENERATED by kinoko/build.sh from model/common.lua and model/$variant.lua."
    echo "-- Edit those files, then run kinoko/build.sh --models-only."
    echo
    cat model/common.lua
    echo
    cat "model/$variant.lua"
  } >"$variant/model.lua"
  echo "wrote $variant/model.lua"
done
[ "${1-}" = --models-only ] && exit 0

docker build --platform linux/amd64 --build-arg "SWARM_IMAGE=$SWARM_IMAGE" \
  -t "kinoko-swarm:$SWARM_TAG" images/swarm
docker build --platform linux/amd64 -t kinoko-swarm-postgres:pg18 images/postgres
docker image ls --format '{{.Repository}}:{{.Tag}}  {{.Size}}' | grep '^kinoko-swarm'
