#!/usr/bin/env bun
/**
 * Generate src/openapi.gen.ts from the repo's openapi.json, keeping only the
 * operations the client calls and the component schemas they reference. The
 * full spec types are ~1.5 MB; this keeps the published package small.
 *
 * Usage: bun run --cwd packages/agent-swarm-sdk gen:types
 * `bun run docs:openapi` (repo root) runs it after regenerating openapi.json.
 */
import { join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

/** Path -> methods the client calls. Add an entry here when the client grows. */
const OPERATIONS: Record<string, string[]> = {
  "/api/tasks": ["post"],
  "/api/tasks/{id}": ["get"],
  "/api/agents": ["get"],
  "/api/memory/search": ["post"],
  "/api/scripts/run": ["post"],
};

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type Spec = {
  paths: Record<string, Record<string, Json>>;
  components: { schemas: Record<string, Json>; securitySchemes?: Json };
};

const pkgRoot = join(import.meta.dir, "..");
const spec = (await Bun.file(join(pkgRoot, "../../openapi.json")).json()) as Spec;

const paths: Spec["paths"] = {};
for (const [path, methods] of Object.entries(OPERATIONS)) {
  const item = spec.paths[path];
  if (!item) throw new Error(`openapi.json has no path ${path}`);
  paths[path] = {};
  for (const method of methods) {
    const op = item[method];
    if (!op) throw new Error(`openapi.json has no ${method.toUpperCase()} ${path}`);
    paths[path][method] = op;
  }
}

// Collect every component schema reachable from the kept operations.
const schemas: Record<string, Json> = {};
const visit = (node: Json): void => {
  if (Array.isArray(node)) {
    for (const child of node) visit(child);
    return;
  }
  if (node === null || typeof node !== "object") return;
  const ref = node.$ref;
  if (typeof ref === "string" && ref.startsWith("#/components/schemas/")) {
    const name = ref.slice("#/components/schemas/".length);
    const schema = spec.components.schemas[name];
    if (schema === undefined) throw new Error(`openapi.json has no schema ${name}`);
    if (!(name in schemas)) {
      schemas[name] = schema;
      visit(schema);
    }
  }
  for (const child of Object.values(node)) visit(child);
};
visit(paths);

const sorted = Object.fromEntries(Object.entries(schemas).sort(([a], [b]) => a.localeCompare(b)));
const filtered = {
  ...spec,
  paths,
  components: { schemas: sorted, securitySchemes: spec.components.securitySchemes ?? {} },
};

const body = astToString(await openapiTS(JSON.stringify(filtered)));
const header =
  "// Generated by packages/agent-swarm-sdk/scripts/gen-types.ts from openapi.json. Do not edit.\n" +
  "// Regenerate with `bun run docs:openapi` (repo root).\n\n";
await Bun.write(join(pkgRoot, "src/openapi.gen.ts"), header + body);
console.log(
  `Generated @desplega.ai/agent-swarm-sdk types: ${Object.keys(paths).length} paths, ${Object.keys(sorted).length} schemas`,
);
