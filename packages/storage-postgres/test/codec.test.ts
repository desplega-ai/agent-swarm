import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { ClassifiedTimestampFormats, createPostgresClient, type PostgresClient } from "../src";
import { createScratchDatabase, type ScratchDatabase } from "./scratch";

// The read codec returns rows in the SQLite value shape (decision D8).

let scratch: ScratchDatabase;
let client: PostgresClient;
const formats = new ClassifiedTimestampFormats([
  { table: "v", column: "isoAt", format: "iso-ms-z" },
  { table: "v", column: "spaceAt", format: "space" },
]);

beforeAll(async () => {
  scratch = await createScratchDatabase("codec");
  client = createPostgresClient(scratch.url, { max: 2, timestampFormats: formats });
  await client.run(`CREATE TABLE v (
    id text PRIMARY KEY, flag boolean, big bigint, doc jsonb, "isoAt" timestamptz,
    "spaceAt" timestamptz, digits text, blob bytea, ratio double precision)`);
  formats.resolve(
    await client.query(`
      SELECT c.oid::int AS oid, a.attnum::int AS attnum,
             CASE a.attname WHEN 'spaceAt' THEN 'space' ELSE 'iso-ms-z' END AS format
      FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
      WHERE c.relname = 'v' AND a.attname IN ('isoAt', 'spaceAt')`),
  );
});

afterAll(async () => {
  await client.close();
  await scratch.drop();
});

describe("postgres read codec", () => {
  test("flags, big integers, JSON, timestamps and text come back in the SQLite shape", async () => {
    await client.run(`INSERT INTO v VALUES ($1, $2, $3, $4::text::jsonb, $5, $6, $7, $8, $9)`, [
      "a",
      true,
      "9007199254740991",
      '{"k":[1,2]}',
      "2026-11-20T10:00:00.123Z",
      "2026-11-20 10:00:00",
      "0042",
      new Uint8Array([1, 2]),
      0.5,
    ]);
    const row = await client.get<Record<string, unknown>>(`SELECT * FROM v WHERE id = 'a'`);
    expect(row).toMatchObject({
      flag: 1,
      big: 9007199254740991,
      doc: '{"k":[1,2]}',
      isoAt: "2026-11-20T10:00:00.123Z",
      spaceAt: "2026-11-20 10:00:00",
      digits: "0042",
      ratio: 0.5,
    });
    expect([...(row?.blob as Uint8Array)]).toEqual([1, 2]);
  });

  test("aggregates and aliased expressions decode by type; an aliased timestamp keeps its column format by name", async () => {
    const row = await client.get<Record<string, unknown>>(
      `SELECT count(*) AS n, bool_or(flag) AS anyflag, max("spaceAt") AS "spaceAt" FROM v`,
    );
    expect(row).toEqual({ n: 1, anyflag: 1, spaceAt: "2026-11-20 10:00:00" });
  });

  test("_rowid is dropped from results unless selected under another name", async () => {
    await client.run(
      `CREATE TABLE r (id text PRIMARY KEY, "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL)`,
    );
    await client.run(`INSERT INTO r (id) VALUES ('x')`);
    expect(await client.get(`SELECT * FROM r`)).toEqual({ id: "x" });
    expect(await client.get(`SELECT id, "_rowid" AS seq FROM r`)).toEqual({ id: "x", seq: 1 });
  });

  test("NULLs stay NULL", async () => {
    await client.run(`INSERT INTO v (id) VALUES ('n')`);
    const row = await client.get<Record<string, unknown>>(
      `SELECT flag, big, doc, "isoAt" FROM v WHERE id = 'n'`,
    );
    expect(row).toEqual({ flag: null, big: null, doc: null, isoAt: null });
  });
});
