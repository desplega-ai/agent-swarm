import { afterAll, afterEach, beforeEach, describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { CopyCell, CopyRow, CopySource, CopyTable } from "@desplega/storage";
import { copyIntoPostgres } from "../src/data-copy";
import { createScratchDatabase, type ScratchDatabase } from "./scratch";

/**
 * Decision D11: the copy into Postgres. A small chain stands in for the swarm
 * schema: `items` covers each converted type, `seeded` holds a row the chain
 * inserts, `children` has a deferrable foreign key, and `items` has a user
 * trigger that refuses every write while it is enabled.
 */

const CHAIN = `
CREATE TABLE items (
  id text PRIMARY KEY,
  flag boolean NOT NULL,
  doc jsonb,
  at timestamptz,
  n bigint,
  ratio double precision,
  raw bytea,
  note text,
  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE
);
CREATE TABLE seeded (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
INSERT INTO seeded (name) VALUES ('from the chain');
CREATE TABLE children (
  id text PRIMARY KEY,
  item text NOT NULL REFERENCES items (id) DEFERRABLE INITIALLY IMMEDIATE,
  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE
);
CREATE FUNCTION refuse_write() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'trigger fired'; END $$;
CREATE TRIGGER items_refuse BEFORE INSERT ON items FOR EACH ROW EXECUTE FUNCTION refuse_write();
`;

const enc = new TextEncoder();
const text = (value: string): CopyCell => ({ kind: "text", bytes: enc.encode(value) });
const int = (value: number): CopyCell => ({ kind: "integer", value: BigInt(value) });
const NULL: CopyCell = { kind: "null" };

const ITEMS: CopyTable = {
  name: "items",
  hasRowid: true,
  columns: ["id", "flag", "doc", "at", "n", "ratio", "raw", "note"].map((name) => ({
    name,
    declaredType: "",
  })),
};
const SEEDED: CopyTable = {
  name: "seeded",
  hasRowid: true,
  columns: [
    { name: "id", declaredType: "INTEGER" },
    { name: "name", declaredType: "TEXT" },
  ],
};
const CHILDREN: CopyTable = {
  name: "children",
  hasRowid: true,
  columns: [
    { name: "id", declaredType: "TEXT" },
    { name: "item", declaredType: "TEXT" },
  ],
};

function item(rowid: number, cells: CopyCell[]): CopyRow {
  return { rowid: BigInt(rowid), label: `rowid ${rowid}`, cells };
}

function goodItems(): CopyRow[] {
  return [
    item(3, [
      text("a"),
      int(1),
      text('{"b":1,"a":[1,"x",null]}'),
      text("2026-11-20T10:00:00.123Z"),
      { kind: "integer", value: 9_007_199_254_740_993n },
      { kind: "real", value: 0.25 },
      { kind: "blob", bytes: new Uint8Array([0, 1, 255]) },
      text("ünïcødé 日本"),
    ]),
    item(7, [text("b"), int(0), NULL, text("2026-11-20 10:00:00"), NULL, NULL, NULL, NULL]),
  ];
}

function source(
  tables: Record<string, { table: CopyTable; rows: CopyRow[] }>,
  head = 1,
): CopySource {
  return {
    migrationHead: () => head,
    tables: () => Object.values(tables).map((t) => t.table),
    skippedTables: () => [],
    *rows(table, batchSize) {
      const rows = tables[table.name]?.rows ?? [];
      for (let i = 0; i < rows.length; i += batchSize) yield rows.slice(i, i + batchSize);
    },
    close() {},
  };
}

function fullSource(items: CopyRow[] = goodItems(), children: CopyRow[] = []) {
  return source({
    items: { table: ITEMS, rows: items },
    seeded: { table: SEEDED, rows: [item(5, [int(5), text("from the source")])] },
    children: { table: CHILDREN, rows: children },
  });
}

let dir: string;
let db: ScratchDatabase;
let sql: InstanceType<typeof Bun.SQL>;
const scratch: ScratchDatabase[] = [];

beforeEach(async () => {
  dir = mkdtempSync(join(tmpdir(), "copy-chain-"));
  writeFileSync(join(dir, "001_chain.sql"), CHAIN);
  db = await createScratchDatabase("copy");
  scratch.push(db);
  sql = new Bun.SQL({ url: db.url, max: 1 });
});

afterEach(async () => {
  await sql.close();
  rmSync(dir, { recursive: true, force: true });
});

afterAll(async () => {
  for (const s of scratch) await s.drop();
});

const run = (src: CopySource) =>
  copyIntoPostgres(src, { url: db.url, migrationsDir: dir, embeddingDimensions: 4, log: () => {} });

describe("copyIntoPostgres", () => {
  test("copies every type, keeps rowids, compares equal, restarts sequences", async () => {
    const report = await run(fullSource(goodItems(), [item(1, [text("c1"), text("a")])]));
    expect(report.error).toBeUndefined();
    expect(report.ok).toBe(true);
    expect(report.tables.map((t) => [t.table, t.sourceRows, t.equal])).toEqual([
      ["items", 2, true],
      ["seeded", 1, true],
      ["children", 1, true],
    ]);
    const rows = await sql.unsafe(
      `SELECT id, flag, doc, at, n::text AS n, ratio, encode(raw, 'hex') AS raw, note, "_rowid"::int AS r
         FROM items ORDER BY id`,
    );
    expect(rows[0]).toEqual({
      id: "a",
      flag: true,
      doc: { a: [1, "x", null], b: 1 },
      at: new Date("2026-11-20T10:00:00.123Z"),
      n: "9007199254740993",
      ratio: 0.25,
      raw: "0001ff",
      note: "ünïcødé 日本",
      r: 3,
    });
    // Text with no zone is UTC, as SQLite reads it.
    expect(rows[1].at).toEqual(new Date("2026-11-20T10:00:00.000Z"));
    // The chain's seeded row is replaced by the source's.
    expect(await sql.unsafe("SELECT id::int AS id, name FROM seeded")).toEqual([
      { id: 5, name: "from the source" },
    ]);
    const next = await sql.unsafe(
      "INSERT INTO seeded (name) VALUES ('next') RETURNING id::int AS id",
    );
    expect(next[0].id).toBe(6);
    // The user trigger is back on.
    await expect(sql.unsafe(`INSERT INTO items (id, flag) VALUES ('z', true)`)).rejects.toThrow(
      /trigger fired/,
    );
  });

  test("reports each value Postgres cannot store and writes nothing", async () => {
    const bad = [
      item(1, [text("nul"), int(1), NULL, NULL, NULL, NULL, NULL, text("a\u0000b")]),
      item(2, [
        text("utf8"),
        int(1),
        NULL,
        NULL,
        NULL,
        NULL,
        NULL,
        { kind: "text", bytes: new Uint8Array([0xc3, 0x28]) },
      ]),
      item(3, [text("ts"), int(1), NULL, text("2026-13-45 99:00:00"), NULL, NULL, NULL, NULL]),
      item(4, [text("flag"), int(2), NULL, NULL, NULL, NULL, NULL, NULL]),
      item(5, [text("json"), int(1), text('{"a":"\\u0000"}'), NULL, NULL, NULL, NULL, NULL]),
      item(6, [text("broken"), int(1), text("{nope"), NULL, NULL, NULL, NULL, NULL]),
      item(7, [text("nullflag"), NULL, NULL, NULL, NULL, NULL, NULL, NULL]),
    ];
    const report = await run(fullSource(bad));
    expect(report.ok).toBe(false);
    expect(report.problems.map((p) => [p.row, p.column, p.reason.split(":")[0]])).toEqual([
      ["rowid 1", "note", "NUL byte in text"],
      ["rowid 2", "note", "invalid UTF-8"],
      ["rowid 3", "at", "invalid timestamp"],
      ["rowid 4", "flag", "not a flag (0 or 1)"],
      ["rowid 5", "doc", "JSON holds a \\u0000 character"],
      ["rowid 6", "doc", "invalid JSON"],
      ["rowid 7", "flag", "NULL in a NOT NULL column"],
    ]);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM items"))[0].n).toBe(0);
    expect((await sql.unsafe("SELECT name FROM seeded"))[0].name).toBe("from the chain");
  });

  test("a foreign key that fails at the end rolls the copy back", async () => {
    const report = await run(fullSource(goodItems(), [item(1, [text("c1"), text("missing")])]));
    expect(report.ok).toBe(false);
    expect(report.error).toMatch(/nothing was written.*foreign key/);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM items"))[0].n).toBe(0);
  });

  test("a checksum difference rolls the copy back, so a re-run is not refused", async () => {
    // Second precision drops the .123 of the first item: the rows store, but
    // the target checksum differs from the source one.
    writeFileSync(
      join(dir, "001_chain.sql"),
      CHAIN.replace("at timestamptz,", "at timestamptz(0),"),
    );
    const report = await run(fullSource());
    expect(report.ok).toBe(false);
    expect(report.error).toMatch(/checksum differs.*nothing was written/);
    expect(report.tables.find((t) => t.table === "items")?.equal).toBe(false);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM items"))[0].n).toBe(0);
    expect((await sql.unsafe("SELECT name FROM seeded"))[0].name).toBe("from the chain");
    const again = await run(fullSource());
    expect(again.error).toMatch(/checksum differs/);
  });

  test("refuses a target with rows and a source at another migration head", async () => {
    expect((await run(fullSource())).ok).toBe(true);
    const again = await run(fullSource());
    expect(again.ok).toBe(false);
    expect(again.error).toMatch(
      /holds rows \(tables: items, children\)|holds rows \(tables: children, items\)|holds rows \(tables: items\)/,
    );

    const other = await createScratchDatabase("copyhead");
    scratch.push(other);
    const behind = await copyIntoPostgres(
      source({ items: { table: ITEMS, rows: goodItems() } }, 0),
      { url: other.url, migrationsDir: dir, embeddingDimensions: 4, log: () => {} },
    );
    expect(behind.ok).toBe(false);
    expect(behind.error).toMatch(/migration heads differ: source 0, target 1/);
  });
});
