import { afterAll, afterEach, beforeEach, describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { CopyCell, CopyMigration, CopyRow, CopySource, CopyTable } from "@desplega/storage";
import { PROCESS_LOCK_KEY } from "../src/boot";
import { copyIntoPostgres } from "../src/data-copy";
import { runPostgresMigrations } from "../src/migrations";
import { createScratchDatabase, type ScratchDatabase } from "./scratch";

/**
 * Decision D11: the copy into Postgres. A small chain stands in for the swarm
 * schema: `items` covers each converted type, `seeded` holds a row the chain
 * inserts, `children` has a deferrable foreign key, and `items` has a user
 * trigger that refuses every write while it is enabled.
 */

const CHAIN = `
CREATE TABLE items (
  id text PRIMARY KEY,
  flag boolean NOT NULL,
  doc jsonb,
  at timestamptz,
  n bigint,
  ratio double precision,
  raw bytea,
  note text,
  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE
);
CREATE TABLE seeded (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
INSERT INTO seeded (name) VALUES ('from the chain');
CREATE TABLE children (
  id text PRIMARY KEY,
  item text NOT NULL REFERENCES items (id) DEFERRABLE INITIALLY IMMEDIATE,
  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE
);
CREATE FUNCTION refuse_write() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'trigger fired'; END $$;
CREATE TRIGGER items_refuse BEFORE INSERT ON items FOR EACH ROW EXECUTE FUNCTION refuse_write();
`;

const enc = new TextEncoder();
const text = (value: string): CopyCell => ({ kind: "text", bytes: enc.encode(value) });
const int = (value: number): CopyCell => ({ kind: "integer", value: BigInt(value) });
const NULL: CopyCell = { kind: "null" };

const ITEMS: CopyTable = {
  name: "items",
  hasRowid: true,
  columns: ["id", "flag", "doc", "at", "n", "ratio", "raw", "note"].map((name) => ({
    name,
    declaredType: "",
  })),
};
const SEEDED: CopyTable = {
  name: "seeded",
  hasRowid: true,
  columns: [
    { name: "id", declaredType: "INTEGER" },
    { name: "name", declaredType: "TEXT" },
  ],
};
const CHILDREN: CopyTable = {
  name: "children",
  hasRowid: true,
  columns: [
    { name: "id", declaredType: "TEXT" },
    { name: "item", declaredType: "TEXT" },
  ],
};

function item(rowid: number, cells: CopyCell[]): CopyRow {
  return { rowid: BigInt(rowid), label: `rowid ${rowid}`, cells };
}

function goodItems(): CopyRow[] {
  return [
    item(3, [
      text("a"),
      int(1),
      text('{"b":1,"a":[1,"x",null]}'),
      text("2026-11-20T10:00:00.123Z"),
      { kind: "integer", value: 9_007_199_254_740_993n },
      { kind: "real", value: 0.25 },
      { kind: "blob", bytes: new Uint8Array([0, 1, 255]) },
      text("ünïcødé 日本"),
    ]),
    item(7, [text("b"), int(0), NULL, text("2026-11-20 10:00:00"), NULL, NULL, NULL, NULL]),
  ];
}

/** SQLite history: version 0 is older than the test chain, version 1 is the chain's. */
const HISTORY: CopyMigration[] = [
  { version: 0, name: "000_legacy", appliedAt: "2026-01-02T03:04:05.678Z", checksum: "c0" },
  { version: 1, name: "001_chain", appliedAt: "2026-11-20T00:00:00.000Z", checksum: "c1" },
];

function source(
  tables: Record<string, { table: CopyTable; rows: CopyRow[] }>,
  head = 1,
): CopySource {
  return {
    migrationHead: () => head,
    migrationHistory: () => HISTORY,
    tables: () => Object.values(tables).map((t) => t.table),
    skippedTables: () => [],
    *rows(table, batchSize) {
      const rows = tables[table.name]?.rows ?? [];
      for (let i = 0; i < rows.length; i += batchSize) yield rows.slice(i, i + batchSize);
    },
    close() {},
  };
}

function fullSource(items: CopyRow[] = goodItems(), children: CopyRow[] = []) {
  return source({
    items: { table: ITEMS, rows: items },
    seeded: { table: SEEDED, rows: [item(5, [int(5), text("from the source")])] },
    children: { table: CHILDREN, rows: children },
  });
}

let dir: string;
let db: ScratchDatabase;
let sql: InstanceType<typeof Bun.SQL>;
const scratch: ScratchDatabase[] = [];

beforeEach(async () => {
  dir = mkdtempSync(join(tmpdir(), "copy-chain-"));
  writeFileSync(join(dir, "001_chain.sql"), CHAIN);
  db = await createScratchDatabase("copy");
  scratch.push(db);
  sql = new Bun.SQL({ url: db.url, max: 1 });
});

afterEach(async () => {
  await sql.close();
  rmSync(dir, { recursive: true, force: true });
});

afterAll(async () => {
  for (const s of scratch) await s.drop();
});

const run = (src: CopySource) =>
  copyIntoPostgres(src, { url: db.url, migrationsDir: dir, embeddingDimensions: 4, log: () => {} });

describe("copyIntoPostgres", () => {
  test("copies every type, keeps rowids, compares equal, restarts sequences", async () => {
    const report = await run(fullSource(goodItems(), [item(1, [text("c1"), text("a")])]));
    expect(report.error).toBeUndefined();
    expect(report.ok).toBe(true);
    expect(report.tables.map((t) => [t.table, t.sourceRows, t.equal])).toEqual([
      ["items", 2, true],
      ["seeded", 1, true],
      ["children", 1, true],
    ]);
    const rows = await sql.unsafe(
      `SELECT id, flag, doc, at, n::text AS n, ratio, encode(raw, 'hex') AS raw, note, "_rowid"::int AS r
         FROM items ORDER BY id`,
    );
    expect(rows[0]).toEqual({
      id: "a",
      flag: true,
      doc: { a: [1, "x", null], b: 1 },
      at: new Date("2026-11-20T10:00:00.123Z"),
      n: "9007199254740993",
      ratio: 0.25,
      raw: "0001ff",
      note: "ünïcødé 日本",
      r: 3,
    });
    // Text with no zone is UTC, as SQLite reads it.
    expect(rows[1].at).toEqual(new Date("2026-11-20T10:00:00.000Z"));
    // The chain's seeded row is replaced by the source's.
    expect(await sql.unsafe("SELECT id::int AS id, name FROM seeded")).toEqual([
      { id: 5, name: "from the source" },
    ]);
    const next = await sql.unsafe(
      "INSERT INTO seeded (name) VALUES ('next') RETURNING id::int AS id",
    );
    expect(next[0].id).toBe(6);
    // SQLite migrations older than the chain keep their applied_at; the
    // chain's own rows stay as the Postgres runner wrote them.
    const history = await sql.unsafe(
      "SELECT version::int AS v, name, applied_at AS at, checksum FROM _migrations ORDER BY version",
    );
    expect(history[0]).toEqual({
      v: 0,
      name: "000_legacy",
      at: new Date("2026-01-02T03:04:05.678Z"),
      checksum: "c0",
    });
    expect(history.map((r: { v: number }) => r.v)).toEqual([0, 1]);
    expect(history[1].checksum).not.toBe("c1");
    // The user trigger is back on.
    await expect(sql.unsafe(`INSERT INTO items (id, flag) VALUES ('z', true)`)).rejects.toThrow(
      /trigger fired/,
    );
  });

  test("reports each value Postgres cannot store and writes nothing", async () => {
    const bad = [
      item(1, [text("nul"), int(1), NULL, NULL, NULL, NULL, NULL, text("a\u0000b")]),
      item(2, [
        text("utf8"),
        int(1),
        NULL,
        NULL,
        NULL,
        NULL,
        NULL,
        { kind: "text", bytes: new Uint8Array([0xc3, 0x28]) },
      ]),
      item(3, [text("ts"), int(1), NULL, text("2026-13-45 99:00:00"), NULL, NULL, NULL, NULL]),
      item(4, [text("flag"), int(2), NULL, NULL, NULL, NULL, NULL, NULL]),
      item(5, [text("json"), int(1), text('{"a":"\\u0000"}'), NULL, NULL, NULL, NULL, NULL]),
      item(6, [text("broken"), int(1), text("{nope"), NULL, NULL, NULL, NULL, NULL]),
      item(7, [text("nullflag"), NULL, NULL, NULL, NULL, NULL, NULL, NULL]),
      // Date.parse accepts both and rolls them into March; Postgres refuses them.
      item(8, [text("feb30"), int(1), NULL, text("2026-02-30 10:00:00"), NULL, NULL, NULL, NULL]),
      item(9, [text("feb31"), int(1), NULL, text("2026-02-31T10:00:00Z"), NULL, NULL, NULL, NULL]),
    ];
    const report = await run(fullSource(bad));
    expect(report.ok).toBe(false);
    expect(report.problems.map((p) => [p.row, p.column, p.reason.split(":")[0]])).toEqual([
      ["rowid 1", "note", "NUL byte in text"],
      ["rowid 2", "note", "invalid UTF-8"],
      ["rowid 3", "at", "invalid timestamp"],
      ["rowid 4", "flag", "not a flag (0 or 1)"],
      ["rowid 5", "doc", "JSON holds a \\u0000 character"],
      ["rowid 6", "doc", "invalid JSON"],
      ["rowid 7", "flag", "NULL in a NOT NULL column"],
      ["rowid 8", "at", "invalid timestamp"],
      ["rowid 9", "at", "invalid timestamp"],
    ]);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM items"))[0].n).toBe(0);
    expect((await sql.unsafe("SELECT name FROM seeded"))[0].name).toBe("from the chain");
  });

  test("a foreign key that fails at the end rolls the copy back", async () => {
    const report = await run(fullSource(goodItems(), [item(1, [text("c1"), text("missing")])]));
    expect(report.ok).toBe(false);
    expect(report.error).toMatch(/nothing was written.*foreign key/);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM items"))[0].n).toBe(0);
  });

  test("a checksum difference rolls the copy back, so a re-run is not refused", async () => {
    // Second precision drops the .123 of the first item: the rows store, but
    // the target checksum differs from the source one.
    writeFileSync(
      join(dir, "001_chain.sql"),
      CHAIN.replace("at timestamptz,", "at timestamptz(0),"),
    );
    const report = await run(fullSource());
    expect(report.ok).toBe(false);
    expect(report.error).toMatch(/checksum differs.*nothing was written/);
    expect(report.tables.find((t) => t.table === "items")?.equal).toBe(false);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM items"))[0].n).toBe(0);
    expect((await sql.unsafe("SELECT name FROM seeded"))[0].name).toBe("from the chain");
    const again = await run(fullSource());
    expect(again.error).toMatch(/checksum differs/);
  });

  test("refuses a target with rows and a source at another migration head", async () => {
    expect((await run(fullSource())).ok).toBe(true);
    const again = await run(fullSource());
    expect(again.ok).toBe(false);
    expect(again.error).toMatch(/holds rows \(tables: [^)]*\bitems\b/);

    const other = await createScratchDatabase("copyhead");
    scratch.push(other);
    const behind = await copyIntoPostgres(
      source({ items: { table: ITEMS, rows: goodItems() } }, 0),
      { url: other.url, migrationsDir: dir, embeddingDimensions: 4, log: () => {} },
    );
    expect(behind.ok).toBe(false);
    expect(behind.error).toMatch(/migration heads differ: source 0, target null/);
  });

  test("refuses an operator row in a seeded table and keeps it", async () => {
    const pool = new Bun.SQL({ url: db.url, max: 1 });
    try {
      await runPostgresMigrations(pool as never, { migrationsDir: dir, log: () => {} });
    } finally {
      await pool.close();
    }
    // The chain's own seed row alone is no reason to refuse.
    expect((await run(fullSource())).ok).toBe(true);

    const other = await createScratchDatabase("copyseed");
    scratch.push(other);
    const otherSql = new Bun.SQL({ url: other.url, max: 1 });
    try {
      await runPostgresMigrations(otherSql as never, { migrationsDir: dir, log: () => {} });
      await otherSql.unsafe("INSERT INTO seeded (name) VALUES ('operator row')");
      const refused = await copyIntoPostgres(fullSource(), {
        url: other.url,
        migrationsDir: dir,
        embeddingDimensions: 4,
        log: () => {},
      });
      expect(refused.ok).toBe(false);
      expect(refused.error).toMatch(/holds rows \(tables: seeded\)/);
      expect(
        (await otherSql.unsafe("SELECT name FROM seeded ORDER BY id")).map(
          (r: { name: string }) => r.name,
        ),
      ).toEqual(["from the chain", "operator row"]);
    } finally {
      await otherSql.close();
    }
  });

  test("refuses an edited seed row and keeps the edit", async () => {
    const pool = new Bun.SQL({ url: db.url, max: 1 });
    try {
      await runPostgresMigrations(pool as never, { migrationsDir: dir, log: () => {} });
    } finally {
      await pool.close();
    }
    // Same row count and row id as the chain wrote: only the value changed.
    await sql.unsafe("UPDATE seeded SET name = 'operator edit' WHERE id = 1");
    const refused = await run(fullSource());
    expect(refused.ok).toBe(false);
    expect(refused.error).toMatch(/holds rows \(tables: seeded\)/);
    expect(
      (await sql.unsafe("SELECT name FROM seeded ORDER BY id")).map(
        (r: { name: string }) => r.name,
      ),
    ).toEqual(["operator edit"]);
  });

  test("refuses an occupied target at an older head before applying the chain", async () => {
    const pool = new Bun.SQL({ url: db.url, max: 1 });
    try {
      await runPostgresMigrations(pool as never, { migrationsDir: dir, log: () => {} });
    } finally {
      await pool.close();
    }
    await sql.unsafe("UPDATE seeded SET name = 'operator edit' WHERE id = 1");
    // The build's chain is one migration ahead of the target, and it rewrites the seed.
    writeFileSync(join(dir, "002_next.sql"), "UPDATE seeded SET name = 'rewritten by 002';");
    const refused = await copyIntoPostgres(
      { ...fullSource(), migrationHead: () => 2 },
      { url: db.url, migrationsDir: dir, embeddingDimensions: 4, log: () => {} },
    );
    expect(refused.ok).toBe(false);
    expect(refused.error).toMatch(/holds rows \(tables: seeded\)/);
    expect((await sql.unsafe("SELECT MAX(version)::int AS v FROM _migrations"))[0].v).toBe(1);
    expect((await sql.unsafe("SELECT name FROM seeded"))[0].name).toBe("operator edit");
  });

  test("a late rollback leaves the target sequence where it was", async () => {
    const pool = new Bun.SQL({ url: db.url, max: 1 });
    try {
      await runPostgresMigrations(pool as never, { migrationsDir: dir, log: () => {} });
    } finally {
      await pool.close();
    }
    // A duplicate history row fails the copy after the sequences restarted.
    const src = {
      ...fullSource(),
      migrationHistory: () => [
        HISTORY[0] as CopyMigration,
        HISTORY[0] as CopyMigration,
        ...HISTORY.slice(1),
      ],
    };
    const report = await run(src);
    expect(report.ok).toBe(false);
    expect(report.error).toMatch(/nothing was written/);
    const next = await sql.unsafe(
      "INSERT INTO seeded (name) VALUES ('next') RETURNING id::int AS id",
    );
    expect(next[0].id).toBe(2);
  });

  test("carries an AUTOINCREMENT counter above 2^53 exactly", async () => {
    const src = {
      ...fullSource(),
      autoincrementCounters: () => ({ seeded: 9_007_199_254_740_993n }),
    };
    const report = await run(src);
    expect(report.error).toBeUndefined();
    const next = await sql.unsafe(
      "INSERT INTO seeded (name) VALUES ('next') RETURNING id::text AS id",
    );
    expect(next[0].id).toBe("9007199254740994");
  });

  test("refuses while another session holds the one-process lock", async () => {
    const holder = new Bun.SQL({ url: db.url, max: 1 });
    try {
      await holder.unsafe("SELECT pg_advisory_lock($1)", [PROCESS_LOCK_KEY]);
      const report = await run(fullSource());
      expect(report.ok).toBe(false);
      expect(report.error).toMatch(/an API process holds the target database/);
      expect(
        (await sql.unsafe("SELECT count(*)::int AS n FROM pg_class WHERE relname = 'items'"))[0].n,
      ).toBe(0);
    } finally {
      await holder.close();
    }
  });

  test("keeps a leading U+FEFF in a text value", async () => {
    const bom = new Uint8Array([0xef, 0xbb, 0xbf, 0x78]);
    const rows = [
      item(1, [text("bom"), int(1), NULL, NULL, NULL, NULL, NULL, { kind: "text", bytes: bom }]),
    ];
    const report = await run(fullSource(rows));
    expect(report.error).toBeUndefined();
    const stored = await sql.unsafe(
      "SELECT note, encode(convert_to(note, 'UTF8'), 'hex') AS hex FROM items WHERE id = 'bom'",
    );
    expect(stored[0]).toEqual({ note: "\uFEFFx", hex: "efbbbf78" });
  });

  test("carries the AUTOINCREMENT counter past the largest surviving key", async () => {
    // SQLite gave keys up to 9 to `seeded`; rows 6 to 9 were deleted since.
    const src = { ...fullSource(), autoincrementCounters: () => ({ seeded: 9 }) };
    const report = await run(src);
    expect(report.error).toBeUndefined();
    const next = await sql.unsafe(
      "INSERT INTO seeded (name) VALUES ('next') RETURNING id::int AS id",
    );
    expect(next[0].id).toBe(10);
  });

  test("refuses embeddings of another width and names the setting", async () => {
    writeFileSync(
      join(dir, "001_chain.sql"),
      `${CHAIN}
CREATE EXTENSION IF NOT EXISTS vector;
CREATE TABLE agent_memory (
  id text PRIMARY KEY,
  embedding bytea,
  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE
);
CREATE TABLE memory_vec (memory_id text PRIMARY KEY, embedding vector);
`,
    );
    const MEMORY: CopyTable = {
      name: "agent_memory",
      hasRowid: true,
      columns: [
        { name: "id", declaredType: "TEXT" },
        { name: "embedding", declaredType: "BLOB" },
      ],
    };
    const embedding = (seed: number) => ({
      kind: "blob" as const,
      bytes: new Uint8Array(new Float32Array(8).map((_, i) => seed + i / 10).buffer),
    });
    const memorySource = () =>
      source({
        items: { table: ITEMS, rows: goodItems() },
        seeded: { table: SEEDED, rows: [] },
        children: { table: CHILDREN, rows: [] },
        agent_memory: {
          table: MEMORY,
          rows: [item(1, [text("m1"), embedding(1)]), item(2, [text("m2"), embedding(2)])],
        },
      });

    const refused = await run(memorySource());
    expect(refused.ok).toBe(false);
    expect(refused.error).toMatch(/have 8 dimensions, but this copy indexes 4/);
    expect(refused.error).toMatch(/EMBEDDING_DIMENSIONS=8/);
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM agent_memory"))[0].n).toBe(0);

    const copied = await copyIntoPostgres(memorySource(), {
      url: db.url,
      migrationsDir: dir,
      embeddingDimensions: 8,
      log: () => {},
    });
    expect(copied.error).toBeUndefined();
    expect((await sql.unsafe("SELECT count(*)::int AS n FROM memory_vec"))[0].n).toBe(2);
  });

  test("ports the stock metric queries, keeps edits, and flags a query Postgres cannot run", async () => {
    writeFileSync(
      join(dir, "001_chain.sql"),
      `${CHAIN}
CREATE TABLE metrics (
  id text PRIMARY KEY,
  "agentId" text,
  slug text NOT NULL,
  definition jsonb NOT NULL,
  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE
);
`,
    );
    const stock = {
      sqlite: {
        sql: "SELECT COUNT(*) AS n FROM items WHERE note = ? COLLATE NOCASE",
        params: ["x"],
      },
      postgres: {
        sql: "SELECT COUNT(*) AS n FROM items WHERE lower(note) = lower($1)",
        params: ["x"],
      },
    };
    writeFileSync(join(dir, "metric-query-ports.json"), JSON.stringify({ ports: [stock] }));
    const METRICS: CopyTable = {
      name: "metrics",
      hasRowid: true,
      columns: ["id", "agentId", "slug", "definition"].map((name) => ({ name, declaredType: "" })),
    };
    const definition = {
      title: "Operator title",
      widgets: [
        { id: "stock", title: "Edited widget title", query: stock.sqlite },
        { id: "portable", query: { sql: "SELECT 1 AS one" } },
        { id: "sqlite-only", query: { sql: "SELECT strftime('%s', 'now') AS t" } },
      ],
    };
    const report = await run(
      source({
        items: { table: ITEMS, rows: goodItems() },
        seeded: { table: SEEDED, rows: [] },
        children: { table: CHILDREN, rows: [] },
        metrics: {
          table: METRICS,
          rows: [
            item(1, [text("m1"), text("system"), text("dash"), text(JSON.stringify(definition))]),
          ],
        },
      }),
    );
    expect(report.error).toBeUndefined();
    expect(report.rebuilt).toContainEqual(expect.objectContaining({ table: "metrics", rows: 1 }));
    const stored = (await sql.unsafe("SELECT definition FROM metrics WHERE id = 'm1'"))[0]
      .definition as typeof definition;
    expect(stored.title).toBe("Operator title");
    expect(stored.widgets[0]).toEqual({
      id: "stock",
      title: "Edited widget title",
      query: stock.postgres,
    });
    expect(stored.widgets[1]?.query).toEqual({ sql: "SELECT 1 AS one" });
    expect(stored.widgets[2]?.query).toEqual(definition.widgets[2]?.query);
    expect(report.attention?.map((a) => [a.table, a.row, a.column])).toEqual([
      ["metrics", "dash (agent system)", "widget sqlite-only"],
    ]);
  });
});
