import { afterAll, beforeAll, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { CopyCell, CopyRow, CopySource, CopyTable } from "@desplega/storage";
import { createPostgresClient, runPostgresMigrations } from "../src";
import { copyIntoPostgres } from "../src/data-copy";
import { createScratchDatabase, type ScratchDatabase } from "./scratch";

/**
 * The copy converts each value by the Postgres type of its column, and compares
 * a normal form of both sides (`convertCell`, `normalizeValue`, `targetExpression`
 * in src/data-copy.ts). A type with no conversion is refused only when a non-null
 * value arrives: a new column type passes the e2e copy when the scenario data
 * leaves that column empty, and fails on the first real database.
 *
 * This test reads the column types of the real chain from a migrated database
 * and copies values of each type through `copyIntoPostgres`. A type with no
 * sample below fails here, so a new type arrives with its conversion.
 */

const CHAIN_DIR = join(import.meta.dir, "../../../src/be/migrations/postgres");

/** Tables the copy fills by other means: no cell of them is converted. */
const NOT_COPIED = new Set(["_migrations", "memory_vec", "memory_fts", "agent_tasks_search"]);

const enc = new TextEncoder();
const text = (value: string): CopyCell => ({ kind: "text", bytes: enc.encode(value) });
const int = (value: bigint): CopyCell => ({ kind: "integer", value });
const real = (value: number): CopyCell => ({ kind: "real", value });

/** SQLite values for each Postgres type (`pg_type.typname`) the chain uses. */
const SAMPLES: Record<string, CopyCell[]> = {
  text: [text("plain"), text("ünïcødé 日本語 🚀 'quote' \\ backslash"), text("")],
  int8: [int(0n), int(-1n), int(9_007_199_254_740_993n), real(42)],
  float8: [real(0.1), real(-2.5e-7), int(3n)],
  bool: [int(1n), int(0n)],
  jsonb: [text('{"b":1,"a":[1,"x",null,true],"nested":{"z":0.5}}'), text("[]"), text('"text"')],
  // Both formats SQLite holds: ISO with milliseconds and Z, and `datetime('now')`.
  timestamptz: [text("2026-11-23T10:00:00.123Z"), text("2026-11-23 10:00:00")],
  bytea: [{ kind: "blob", bytes: new Uint8Array([0, 1, 254, 255]) }, text("stored as text")],
};

type ColumnType = { typname: string; type: string; example: string };

let chain: ScratchDatabase;
let target: ScratchDatabase;
let dir: string;
let types: ColumnType[];

beforeAll(async () => {
  chain = await createScratchDatabase("copytypes");
  target = await createScratchDatabase("copyprobe");
  dir = mkdtempSync(join(tmpdir(), "copy-types-"));
  const db = createPostgresClient(chain.url, { max: 1 });
  try {
    await runPostgresMigrations(db, { migrationsDir: CHAIN_DIR, log: () => {}, warn: () => {} });
    types = await db.query<ColumnType>(
      `SELECT t.typname AS "typname", format_type(a.atttypid, a.atttypmod) AS "type",
              min(c.relname || '.' || a.attname) AS "example"
         FROM pg_attribute a
         JOIN pg_class c ON c.oid = a.attrelid
         JOIN pg_namespace n ON n.oid = c.relnamespace
         JOIN pg_type t ON t.oid = a.atttypid
        WHERE n.nspname = current_schema() AND c.relkind IN ('r', 'p')
          AND a.attnum > 0 AND NOT a.attisdropped AND a.attgenerated = ''
          AND c.relname <> ALL ($1::text[])
        GROUP BY 1, 2 ORDER BY 2`,
      [`{${[...NOT_COPIED].join(",")}}`],
    );
  } finally {
    await db.close();
  }
});

afterAll(async () => {
  rmSync(dir, { recursive: true, force: true });
  await chain.drop();
  await target.drop();
});

test("every column type of the Postgres chain has a data-copy sample", () => {
  expect(types.length).toBeGreaterThan(0);
  const missing = types
    .filter((column) => !SAMPLES[column.typname])
    .map((column) => `${column.type} (${column.example})`);
  // A new type: add its conversion to convertCell, its normal form to normalizeValue
  // and targetExpression (src/data-copy.ts), then its SQLite values to SAMPLES.
  expect(missing).toEqual([]);
});

test("a value of every column type of the Postgres chain copies and compares equal", async () => {
  const columns = types.filter((column) => SAMPLES[column.typname]);
  writeFileSync(
    join(dir, "001_types.sql"),
    `CREATE TABLE type_probe (\n${columns.map((column, i) => `  "c${i}" ${column.type},`).join("\n")}\n` +
      `  "_rowid" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE\n);\n`,
  );
  const table: CopyTable = {
    name: "type_probe",
    hasRowid: true,
    columns: columns.map((_, i) => ({ name: `c${i}`, declaredType: "" })),
  };
  const samples = columns.map((column) => SAMPLES[column.typname] as CopyCell[]);
  const rows: CopyRow[] = Array.from(
    { length: Math.max(...samples.map((cells) => cells.length)) },
    (_, r) => ({
      rowid: BigInt(r + 1),
      label: `rowid ${r + 1}`,
      cells: samples.map((cells) => cells[r % cells.length] as CopyCell),
    }),
  );
  const source: CopySource = {
    migrationHead: () => 1,
    migrationHistory: () => [],
    tables: () => [table],
    skippedTables: () => [],
    *rows() {
      yield rows;
    },
    close() {},
  };
  const report = await copyIntoPostgres(source, {
    url: target.url,
    migrationsDir: dir,
    embeddingDimensions: 4,
    log: () => {},
  });
  // A refused value names its column: map it back to the chain's type.
  expect(
    report.problems.map((p) => `${columns[Number(p.column.slice(1))]?.type}: ${p.reason}`),
  ).toEqual([]);
  expect(report.error).toBeUndefined();
  expect(report.ok).toBe(true);
  expect(report.tables).toHaveLength(1);
  expect(report.tables[0]).toMatchObject({
    sourceRows: rows.length,
    targetRows: rows.length,
    equal: true,
  });
});
