// M0 step 7: classify timestamp-like columns at the SQLite head schema by the format their
// DEFAULT produces. Columns with no default get the format the app writes (not classified here).
// Run from repo root: bun thoughts/taras/research/spikes/ts-columns.ts
import { Database } from "bun:sqlite";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { runMigrations } from "../../../../src/be/migrations/runner";

const dir = mkdtempSync(join(tmpdir(), "pg-ts-cols-"));
const db = new Database(join(dir, "x.sqlite"), { create: true });
const dbg = console.debug;
console.debug = () => {};
try {
  runMigrations(db);
} finally {
  console.debug = dbg;
}
type Col = { name: string; type: string; notnull: number; dflt_value: string | null; pk: number };
const master = db
  .query<{ type: string; name: string; sql: string | null }, []>(
    "SELECT type, name, sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%'",
  )
  .all();
const tables = master
  .filter((r) => r.type === "table")
  .map((r) => r.name)
  .sort();
const ftsShadow = (n: string) =>
  /_fts(_|$)|_vec(_|$)/.test(n) && !master.find((r) => r.name === n)?.sql?.includes("VIRTUAL");
const classes: Record<string, string[]> = {
  "iso-z (strftime %Y-%m-%dT%H:%M:%fZ)": [],
  "space (datetime('now') / CURRENT_TIMESTAMP)": [],
  "other default": [],
  "no default (app-written)": [],
};
const typeCount: Record<string, number> = {};
let cols = 0;
for (const t of tables) {
  for (const c of db.query<Col, []>(`PRAGMA table_info("${t.replaceAll('"', '""')}")`).all()) {
    cols++;
    typeCount[c.type || "(none)"] = (typeCount[c.type || "(none)"] ?? 0) + 1;
    if (
      !/(At|_at|Date|_date|Time|time)$/.test(c.name) &&
      !/strftime|datetime|CURRENT_TIMESTAMP/i.test(c.dflt_value ?? "")
    )
      continue;
    const d = c.dflt_value ?? "";
    const k = /strftime\('%Y-%m-%dT%H:%M:%fZ'/.test(d)
      ? "iso-z (strftime %Y-%m-%dT%H:%M:%fZ)"
      : /datetime\('now'\)|CURRENT_TIMESTAMP/i.test(d)
        ? "space (datetime('now') / CURRENT_TIMESTAMP)"
        : d
          ? "other default"
          : "no default (app-written)";
    classes[k]!.push(`${t}.${c.name}${d && k === "other default" ? ` = ${d}` : ""}`);
  }
}
console.log("# Timestamp columns at the SQLite head schema\n");
console.log(
  "Generated by `bun thoughts/taras/research/spikes/ts-columns.ts`. A column is listed when its name ends in At/_at/Date/Time or its default calls a SQLite date function.\n",
);
console.log(
  `Head schema: ${tables.length} tables (${tables.filter(ftsShadow).length} FTS/vec shadow), ${master.filter((r) => r.type === "index").length} indexes, ${master.filter((r) => r.type === "trigger").length} triggers, ${master.filter((r) => r.type === "view").length} views, ${cols} columns.\n`,
);
console.log(
  `Declared column types: ${Object.entries(typeCount)
    .sort((a, b) => b[1] - a[1])
    .map(([k, v]) => `${k} ${v}`)
    .join(", ")}\n`,
);
for (const [k, v] of Object.entries(classes)) {
  console.log(`## ${k}: ${v.length}\n`);
  for (const x of v) console.log(`- \`${x}\``);
  console.log("");
}
console.log(
  "Invalid-timestamp scan of real data: not run. No copy of production data was supplied (brief M0.7 makes it conditional).",
);
db.close();
rmSync(dir, { recursive: true, force: true });
