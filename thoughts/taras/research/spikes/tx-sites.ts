// M0 step 6: list every `.transaction(` site in src/ (non-test) and mark callbacks that
// (a) call a known side effect, or (b) catch an error inside the callback (a constraint
// catch that continues fails on Postgres after the statement aborts the transaction).
// Heuristic: the callback body is found by bracket matching from the call's "(".
// Output: markdown table on stdout. Run from repo root.
const SIDE =
  /\b(fetch\(|\.emit\(|publish\w*\(|broadcast\w*\(|\bbus\.|eventBus|Bun\.spawn|spawn\(|setTimeout\(|setInterval\(|queueMicrotask\(|ensure\(|dispatch(Pre|Post)\(|sendSlack|postMessage|\.send\(|notify\w*\(|Bun\.write\(|writeFile|appendFile|console\.(log|warn|error)|logger\.)/g;
const rows: string[] = [];
let total = 0,
  withSide = 0,
  withCatch = 0;
for await (const f of new Bun.Glob("src/**/*.{ts,tsx}").scan(".")) {
  if (f.startsWith("src/tests/") || f.includes(".test.") || f.startsWith("src/be/migrations/"))
    continue;
  const t = await Bun.file(f).text();
  const re = /\.transaction\(/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(t))) {
    const start = m.index + m[0].length - 1;
    let depth = 0,
      i = start;
    for (; i < t.length; i++) {
      const ch = t[i];
      if (ch === "(" || ch === "{" || ch === "[") depth++;
      else if (ch === ")" || ch === "}" || ch === "]") {
        depth--;
        if (depth === 0) break;
      }
    }
    const body = t.slice(start, i + 1);
    const line = t.slice(0, m.index).split("\n").length;
    const lines = body.split("\n").length;
    const sides = [...new Set((body.match(SIDE) ?? []).map((s) => s.replace(/\($/, "")))];
    const catches = (body.match(/\bcatch\s*[({]/g) ?? []).length;
    const constraintCatch =
      /UNIQUE|constraint|SQLITE_CONSTRAINT|isUniqueViolation|23505/.test(body) && catches > 0;
    total++;
    if (sides.length) withSide++;
    if (catches) withCatch++;
    rows.push(
      `| \`${f}:${line}\` | ${lines} | ${sides.join(", ") || ""} | ${catches ? (constraintCatch ? `${catches} (constraint)` : catches) : ""} |`,
    );
  }
}
console.log(`# Transaction sites at base commit\n`);
console.log(
  `Generated by \`bun thoughts/taras/research/spikes/tx-sites.ts\`. Heuristic: side-effect names and catch blocks found by text inside the callback body.\n`,
);
console.log(
  `- Sites: ${total}\n- Callbacks with a side-effect candidate: ${withSide}\n- Callbacks with a catch block: ${withCatch}\n`,
);
console.log(`| Site | Lines | Side-effect candidates | catch blocks |\n|---|---|---|---|`);
for (const r of rows.sort()) console.log(r);
