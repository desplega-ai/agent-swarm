/**
 * Regenerates src/be/primitives/boards/excalifont-metrics.json: Excalifont
 * advance widths, so the board element builder can size labels without a
 * native canvas in the API image.
 *
 * Run by hand, with an ad-hoc install outside the repo, so `@napi-rs/canvas`
 * (native) never enters the lockfile or the image:
 *
 *   mkdir -p /tmp/xf/ex && cd /tmp/xf && npm i @napi-rs/canvas@0.1
 *   (cd ex && npm pack @excalidraw/excalidraw@0.18.1 && tar xzf excalidraw-excalidraw-0.18.1.tgz)
 *   node --experimental-strip-types scripts/gen-excalifont-metrics.ts /tmp/xf
 *
 * Node, not Bun: under Bun 1.4 this script segfaults, so it uses node:fs, not
 * Bun.write.
 *
 * Excalifont is licensed under the SIL Open Font License 1.1 (its name table);
 * the JSON holds derived metrics only, no glyph data.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

type CanvasModule = {
  createCanvas(
    w: number,
    h: number,
  ): {
    getContext(kind: "2d"): { font: string; measureText(text: string): { width: number } };
  };
  GlobalFonts: { registerFromPath(path: string, family: string): boolean };
};

const dir = process.argv[2];
if (!dir)
  throw new Error(
    "usage: node --experimental-strip-types scripts/gen-excalifont-metrics.ts <dir with node_modules/@napi-rs/canvas and ex/package>",
  );

const canvas = (await import(
  join(resolve(dir), "node_modules/@napi-rs/canvas/index.js")
)) as CanvasModule;
const fontDir = join(resolve(dir), "ex/package/dist/prod/fonts/Excalifont");
// Excalifont ships as unicode-range subsets. @napi-rs/canvas does not fall
// back across files of one family, so each subset gets its own family and a
// glyph is measured in the first subset that has it (not its .notdef width).
const families = readdirSync(fontDir)
  .sort()
  .map((file, i) => {
    const family = `Excalifont${i}`;
    canvas.GlobalFonts.registerFromPath(join(fontDir, file), family);
    return family;
  });

// Widths scale linearly with font size, so one reference size is enough.
const REFERENCE_SIZE = 100;
const ctx = canvas.createCanvas(10, 10).getContext("2d");
const PRIVATE_USE = "\uE000";
const notdef = new Map(
  families.map((family) => {
    ctx.font = `${REFERENCE_SIZE}px ${family}`;
    return [family, ctx.measureText(PRIVATE_USE).width];
  }),
);
function measureGlyph(text: string): number | undefined {
  for (const family of families) {
    ctx.font = `${REFERENCE_SIZE}px ${family}`;
    const width = ctx.measureText(text).width;
    if (width !== notdef.get(family)) return width;
  }
  return undefined;
}

const RANGES: Array<[number, number]> = [
  [0x20, 0x7e], // ASCII
  [0xa0, 0x17f], // Latin-1 and Latin Extended-A
  [0x370, 0x3ff], // Greek
  [0x400, 0x4ff], // Cyrillic
  [0x2010, 0x2027], // dashes, quotes, bullet, ellipsis
  [0x2190, 0x2199], // arrows
];

const widths: Record<string, number> = {};
for (const [from, to] of RANGES) {
  for (let code = from; code <= to; code += 1) {
    // The soft hyphen is invisible and crashes @napi-rs/canvas 0.1 measureText.
    if (code === 0xad) continue;
    const char = String.fromCodePoint(code);
    const width = measureGlyph(char);
    if (width !== undefined) widths[char] = Math.round((width / REFERENCE_SIZE) * 10_000) / 10_000;
  }
}

// Sum-of-advances ignores kerning; report how far off it is on real labels.
const samples = [
  "Request · Slack · GitHub · cron",
  "Lead triages and routes",
  "in_progress worker is running",
  "The quick brown fox jumps over the lazy dog",
  "WAVE Tokyo AVATAR 1234567890",
];
const latin = families.find((family) => {
  ctx.font = `${REFERENCE_SIZE}px ${family}`;
  return ctx.measureText("a").width !== notdef.get(family);
});
let maxError = 0;
for (const sample of samples) {
  ctx.font = `${REFERENCE_SIZE}px ${latin}`;
  const whole = ctx.measureText(sample).width / REFERENCE_SIZE;
  const summed = [...sample].reduce((sum, char) => sum + (widths[char] ?? 0), 0);
  maxError = Math.max(maxError, Math.abs(summed - whole) / whole);
}

const ascii = [...Array(0x7f - 0x20).keys()].map((i) => widths[String.fromCharCode(0x20 + i)] ?? 0);
const output = {
  $comment: "Generated by scripts/gen-excalifont-metrics.ts. Advance width per character, in ems.",
  font: "Excalifont (Excalidraw 0.18.1, SIL OFL 1.1)",
  lineHeight: 1.25,
  fallback: Math.round((ascii.reduce((a, b) => a + b, 0) / ascii.length) * 10_000) / 10_000,
  wide: 1,
  widths,
};
writeFileSync(
  resolve(import.meta.dirname, "../src/be/primitives/boards/excalifont-metrics.json"),
  `${JSON.stringify(output, null, 2)}\n`,
);
console.log(
  `${Object.keys(widths).length} glyphs, max kerning error ${(maxError * 100).toFixed(2)}%`,
);
