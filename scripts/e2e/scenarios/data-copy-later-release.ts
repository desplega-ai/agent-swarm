// A database that `agent-swarm db-copy` made takes later releases. `data-copy` proves the
// copy itself, and `upgrade-base-db` proves that a copied database boots on this build.
// Here the copy boots three times: on this build, then on a later release (this build's
// Postgres chain plus two migrations that do not exist yet), then on that release again.
// The copied rows, the SQLite history the copy carried, the seed rows and the restarted
// keys must hold through all three.

const CHAIN = join(repoRoot, "src/be/migrations/postgres");

// What a later release does to a copied database: a new table with its own key and a
// foreign key into copied rows, a new column and a new CHECK on a copied table (Postgres
// validates it against every copied row), an index built over copied text, then a
// backfill that reads and rewrites the copied rows.
const LATER_SCHEMA = `
CREATE TABLE "e2e_later_release" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "taskId" text NOT NULL REFERENCES "agent_tasks" ("id") ON DELETE CASCADE,
  "note" text NOT NULL
);
ALTER TABLE "agent_tasks" ADD COLUMN "e2eLaterNote" text;
ALTER TABLE "agent_tasks" ADD CONSTRAINT "e2e_later_release_task_check" CHECK (length("task") > 0);
CREATE INDEX "idx_e2e_later_release_task" ON "agent_tasks" ((lower("task")));
`;
const LATER_BACKFILL = `
INSERT INTO "e2e_later_release" ("taskId", "note")
  SELECT "id", 'backfilled' FROM "agent_tasks" ORDER BY "_rowid";
UPDATE "agent_tasks" SET "e2eLaterNote" = 'later:' || "id";
`;

/** This build's Postgres chain plus the two later migrations, in a temporary directory. */
function laterRelease() {
  const dir = mkdtempSync(join(tmpdir(), "e2e-later-release-"));
  const files = readdirSync(CHAIN, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name);
  for (const file of files) cpSync(join(CHAIN, file), join(dir, file));
  const migrations = files.filter((file) => /^\d+_.+\.sql$/.test(file)).sort();
  const ordinals = migrations.map((file) => Number.parseInt(file, 10));
  const head = Math.max(...ordinals);
  // The tables the chain seeds: each top-level INSERT of a migration file.
  const seeded = new Set<string>();
  for (const file of migrations) {
    for (const match of readFileSync(join(CHAIN, file), "utf8").matchAll(/^INSERT INTO "(\w+)"/gm))
      seeded.add(match[1] as string);
  }
  const added = [`${head + 1}_e2e_later_release_schema`, `${head + 2}_e2e_later_release_backfill`];
  writeFileSync(join(dir, `${added[0]}.sql`), LATER_SCHEMA);
  writeFileSync(join(dir, `${added[1]}.sql`), LATER_BACKFILL);
  return { dir, added, seeded: [...seeded].sort(), chainStart: Math.min(...ordinals), head };
}

type Migration = { version: number; name: string; checksum: string; at?: string };

const history = (db: ReadOnlyDb) =>
  db.engine === "postgres"
    ? db.query<Migration>(
        `SELECT version::int AS version, name, checksum, applied_at::text AS at
           FROM _migrations ORDER BY version`,
      )
    : db.query<Migration>("SELECT version, name, checksum FROM _migrations ORDER BY version");

/** Row count and a digest of every row of each seeded table on the copy. */
function seedState(db: ReadOnlyDb, tables: string[]) {
  return new Map(
    tables.map((table) => [
      table,
      db.get<{ n: number; digest: string }>(
        sql`SELECT count(*)::int AS n,
                   COALESCE(md5(string_agg(md5(t::text), ',' ORDER BY md5(t::text))), '') AS digest
              FROM ${sqlIdent(table)} t`,
      ) as { n: number; digest: string },
    ]),
  );
}

/** Each identity column of the copy: its largest key and the next key its sequence gives. */
function sequences(db: ReadOnlyDb) {
  const columns = db.query<{ table: string; column: string; seq: string }>(
    `SELECT c.relname AS "table", a.attname AS "column",
            pg_get_serial_sequence(quote_ident(c.relname), a.attname) AS "seq"
       FROM pg_attribute a
       JOIN pg_class c ON c.oid = a.attrelid
       JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = current_schema() AND c.relkind = 'r'
        AND a.attidentity <> '' AND NOT a.attisdropped
      ORDER BY 1, 2`,
  );
  return db.query<{ table: string; column: string; max: string; next: string }>(
    columns
      .map(
        ({ table, column, seq }) =>
          `SELECT '${table}' AS "table", '${column}' AS "column",
                  (SELECT COALESCE(max("${column}"), 0)::text FROM "${table}") AS "max",
                  (SELECT (CASE WHEN is_called THEN last_value + 1 ELSE last_value END)::text
                     FROM ${seq}) AS "next"`,
      )
      .join(" UNION ALL "),
  );
}

async function snapshot(api: ApiClient, path: string, agentId?: string) {
  const response = await api("GET", path, agentId ? { agentId } : {});
  expectStatus(response, [200], `GET ${path}`);
  // Each API writes its own origin into links; the two APIs listen on different ports.
  return JSON.parse(response.text.replace(/http:\/\/(localhost|127\.0\.0\.1):\d+/g, "<origin>"));
}

async function createTask(api: ApiClient, agentId: string, task: string): Promise<string> {
  const created = await api("POST", "/api/tasks", {
    body: { task, agentId, routingReason: "human_pinned", source: "api" },
  });
  expectStatus(created, [201], `create task "${task}"`);
  return asString(asRecord(created.json).id, "task id");
}

async function indexMemory(api: ApiClient, agentId: string, name: string, content: string) {
  const indexed = await api("POST", "/api/memory/index", {
    agentId,
    body: { content, name, scope: "agent", source: "manual", agentId },
  });
  expectStatus(indexed, [202], `index memory "${name}"`);
  const ids = asRecord(indexed.json).memoryIds;
  return asString(Array.isArray(ids) ? ids[0] : undefined, "memory id");
}

async function searchTasks(api: ApiClient, agentId: string, search: string): Promise<string[]> {
  const query = new URLSearchParams({ agentId, search, limit: "100" });
  const response = await api("GET", `/api/tasks?${query}`);
  expectStatus(response, [200], `task search "${search}"`);
  return asRecords(response.json, "tasks").map((task) => asString(task.id, "task id"));
}

/** Memory id to the arm that found it: `hybrid` when the vector and the keyword arm both did. */
async function searchMemory(api: ApiClient, agentId: string, query: string) {
  const response = await api("POST", "/api/memory/search", {
    agentId,
    body: { query, limit: 20, scope: "agent" },
  });
  expectStatus(response, [200], `memory search "${query}"`);
  return new Map(
    asRecords(response.json, "results").map((row) => [
      asString(row.id, "memory id"),
      String(row.retrievalSource),
    ]),
  );
}

const sameSet = (actual: string[], expected: string[]) =>
  JSON.stringify([...actual].sort()) === JSON.stringify([...expected].sort());

export const dataCopyLaterRelease: Scenario = {
  name: "data-copy-later-release",
  order: 9_015,
  async run(ctx) {
    const later = laterRelease();
    // The mock inference host gives both APIs embeddings, so memory search has a vector arm.
    const pair = await ctx.startDataCopy({ env: ctx.llm.env });
    try {
      // --- Fill the source through its public API.
      const api = pair.source;
      const agentId = randomUUID();
      const registered = await api("POST", "/api/agents", {
        agentId,
        body: { name: `later-worker-${ctx.nonce}`, role: "worker", status: "online" },
      });
      expectStatus(registered, [200, 201], "register agent");
      // One word that no other row holds: full-text search finds exactly these tasks.
      const word = `laterword${ctx.nonce}`;
      const copiedTasks = [
        await createTask(api, agentId, `copied task one ${word}`),
        await createTask(api, agentId, `copied task two ${word} ünïcødé 日本語`),
      ];
      const schedule = await api("POST", "/api/schedules", {
        body: {
          name: `later-schedule-${ctx.nonce}`,
          cronExpression: "0 0 1 1 *",
          taskTemplate: "later schedule task",
          targetAgentId: agentId,
        },
      });
      expectStatus(schedule, [200, 201], "create schedule");
      const scheduleRecord = asRecord(schedule.json);
      const scheduleId = asString(
        asRecord(scheduleRecord.schedule ?? scheduleRecord).id,
        "schedule id",
      );
      const configKey = `LATER_SECRET_${ctx.nonce}`.toUpperCase();
      const config = await api("PUT", "/api/config", {
        body: { scope: "global", key: configKey, value: "later-secret-value", isSecret: true },
      });
      expectStatus(config, [200, 201], "config");
      const kvKey = `later-kv-${ctx.nonce}`;
      const kv = await api("PUT", `/api/kv/${kvKey}`, {
        agentId,
        body: { value: { nested: { b: 2, a: [1, "x", null] } } },
      });
      expectStatus(kv, [200], "kv put");
      const copiedMemory = await indexMemory(
        api,
        agentId,
        `copied memory ${ctx.nonce}`,
        "violet heron lantern meadow anchor biscuit",
      );
      // The embedding is written after the 202. Wait for it on the row itself: the source
      // has a vector index only where SQLite can load sqlite-vec (not on macOS).
      let health: Record<string, unknown> = {};
      const embedded = await pollUntil(
        async () => {
          const response = await api("GET", "/api/memory/health");
          expectStatus(response, [200], "memory health on the source");
          health = asRecord(asRecord(response.json).counts);
          return Number(health.validEmbedding) >= 1;
        },
        20_000,
        200,
      );
      expect(embedded, `the source never embedded its memory: ${JSON.stringify(health)}`);

      // An operator edit of a seed row: a new title on the first starter dashboard widget.
      const editedTitle = `Edited by the operator ${ctx.nonce}`;
      const starterOf = async (client: ApiClient) => {
        const listed = await client("GET", "/api/metrics/definitions?agentId=system&fields=full");
        expectStatus(listed, [200], "list the system metrics");
        const starters = asRecords(listed.json, "metrics").filter(
          (metric) => metric.slug === "swarm-operations-overview",
        );
        expect(starters.length === 1, `${starters.length} starter dashboards, expected 1`);
        return starters[0] as Record<string, unknown>;
      };
      const starter = await starterOf(api);
      const definition = asRecord(starter.definition);
      const widgets = asRecords(definition, "widgets");
      const editedWidget = asString(widgets[0]?.id, "first starter widget id");
      (widgets[0] as Record<string, unknown>).title = editedTitle;
      const edited = await api(
        "PUT",
        `/api/metrics/definitions/${asString(starter.id, "starter id")}`,
        { body: { definition } },
      );
      expectStatus(edited, [200], "edit the starter dashboard on the source");
      const widgetTitle = async (client: ApiClient) =>
        asRecords(asRecord((await starterOf(client)).definition), "widgets").find(
          (widget) => widget.id === editedWidget,
        )?.title;

      const routes: [string, string?][] = [
        [`/api/agents/${agentId}`],
        ...copiedTasks.map((id): [string] => [`/api/tasks/${id}`]),
        [`/api/schedules/${scheduleId}`],
        [`/api/config?scope=global&key=${configKey}&includeSecrets=true`],
        [`/api/kv/${kvKey}`, agentId],
      ];
      const before = new Map<string, unknown>();
      for (const [route, as] of routes) before.set(route, await snapshot(api, route, as));

      // --- Copy, and boot on this build (boot 1).
      const { cli, target, sourceDb, targetDb, restartTarget, targetLog } = await pair.copy();
      expect(
        cli.exitCode === 0 && cli.stdout.includes("every count and checksum equal"),
        `db-copy exited ${cli.exitCode}: ${cli.stderr.slice(-2000)}${cli.stdout.slice(-1000)}`,
      );
      const assertEmptyBus = () => {
        for (const table of ["bus_events", "bus_deliveries"]) {
          expect(
            targetDb.get<{ n: number }>(sql`SELECT count(*) AS n FROM ${sqlIdent(table)}`)?.n === 0,
            `${table} must start empty and remain available after an upgrade`,
          );
        }
      };
      assertEmptyBus();
      const applying = (log: string) =>
        [...log.matchAll(/\[pg-migrations\] Applying: (\S+)/g)].map((match) => match[1] as string);
      const firstLog = await targetLog();
      expect(
        applying(firstLog).length === 0,
        `the API on the copy applied ${applying(firstLog).join(", ")}; the copy recorded the whole chain`,
      );

      // The copy carried every SQLite migration older than the Postgres chain, as it was.
      const legacy = history(sourceDb).filter((row) => row.version < later.chainStart);
      const copiedHistory = history(targetDb);
      expect(legacy.length > 0, "the SQLite source has no migration older than the Postgres chain");
      expect(
        JSON.stringify(
          copiedHistory
            .filter((row) => row.version < later.chainStart)
            .map(({ version, name, checksum }) => ({ version, name, checksum })),
        ) === JSON.stringify(legacy),
        "the copy did not carry the SQLite history older than the Postgres chain as it was",
      );
      expect(
        copiedHistory.at(-1)?.version === later.head,
        `the copy is at migration ${copiedHistory.at(-1)?.version}, this build at ${later.head}`,
      );

      // A row written on the copy before the upgrade: the later backfill must see it too.
      const preUpgradeTask = await createTask(target, agentId, `before the upgrade ${word}`);
      const seedsOnCopy = seedState(targetDb, later.seeded);
      for (const table of later.seeded) {
        const source = sourceDb.get<{ n: number }>(
          sql`SELECT count(*) AS n FROM ${sqlIdent(table)}`,
        )?.n;
        expect(
          seedsOnCopy.get(table)?.n === source,
          `seed table ${table}: ${source} rows in the source, ${seedsOnCopy.get(table)?.n} on the copy`,
        );
      }
      expect(
        (await widgetTitle(target)) === editedTitle,
        "the copy lost the operator's edit of the starter dashboard",
      );

      const assertSeedsHold = (label: string) => {
        const now = seedState(targetDb, later.seeded);
        for (const table of later.seeded) {
          const was = seedsOnCopy.get(table);
          const is = now.get(table);
          expect(
            was?.n === is?.n && was?.digest === is?.digest,
            `${label}: seed table ${table} changed (${was?.n} rows before, ${is?.n} now): a seed row was added again or reset`,
          );
        }
      };
      const assertSearch = async (label: string, tasks: string[], memories: string[]) => {
        const found = await searchTasks(target, agentId, word);
        expect(
          sameSet(found, tasks),
          `${label}: task search "${word}" returned [${found.join(", ")}], expected [${tasks.join(", ")}]`,
        );
        // Memory embedding is asynchronous: a new memory joins the vector arm a moment later.
        let hits = new Map<string, string>();
        const all = await pollUntil(
          async () => {
            hits = await searchMemory(target, agentId, "violet heron");
            return memories.every((id) => hits.get(id) === "hybrid");
          },
          20_000,
          200,
        );
        expect(
          all,
          `${label}: memory search must find [${memories.join(", ")}] by vector and by keyword, got ${JSON.stringify([...hits])}`,
        );
      };
      await assertSearch("on this build", [...copiedTasks, preUpgradeTask], [copiedMemory]);

      // --- A later release boots on the copy (boot 2).
      const laterEnv = { POSTGRES_MIGRATIONS_DIR: later.dir };
      await restartTarget(laterEnv);
      assertEmptyBus();
      const secondLog = await targetLog();
      expect(
        JSON.stringify(applying(secondLog)) === JSON.stringify(later.added),
        `the later release applied [${applying(secondLog).join(", ")}], expected [${later.added.join(", ")}]`,
      );
      expect(
        !secondLog.includes("[pg-migrations] WARNING"),
        `the later release warned about the copied history: ${secondLog.slice(0, 1500)}`,
      );
      const upgraded = history(targetDb);
      expect(
        JSON.stringify(upgraded.slice(0, copiedHistory.length)) === JSON.stringify(copiedHistory),
        "the later release changed migration rows that the copy wrote",
      );
      expect(
        JSON.stringify(upgraded.slice(copiedHistory.length).map((row) => row.name)) ===
          JSON.stringify(later.added),
        `the later release recorded [${upgraded
          .slice(copiedHistory.length)
          .map((row) => row.name)
          .join(", ")}], expected [${later.added.join(", ")}]`,
      );

      // The later migrations ran over the copied rows and the row written on the copy.
      const expectedTasks = [...copiedTasks, preUpgradeTask];
      const backfilled = targetDb
        .query<{ taskId: string; note: string | null }>(
          `SELECT r."taskId" AS "taskId", t."e2eLaterNote" AS "note"
             FROM e2e_later_release r JOIN agent_tasks t ON t.id = r."taskId"`,
        )
        .filter((row) => expectedTasks.includes(row.taskId));
      expect(
        backfilled.length === expectedTasks.length &&
          backfilled.every((row) => row.note === `later:${row.taskId}`),
        `the later backfill reached ${backfilled.length} of ${expectedTasks.length} tasks: ${JSON.stringify(backfilled)}`,
      );

      // Old rows are served as the source served them.
      for (const [route, as] of routes) {
        const after = await snapshot(target, route, as);
        expect(
          Bun.deepEquals(after, before.get(route), true),
          `GET ${route} differs on the later release:\nsource ${JSON.stringify(before.get(route)).slice(0, 1200)}\ntarget ${JSON.stringify(after).slice(0, 1200)}`,
        );
      }
      assertSeedsHold("later release");
      expect(
        (await widgetTitle(target)) === editedTitle,
        "the later release reset the operator's edit of the starter dashboard",
      );

      // New writes on tables whose keys the copy restarted.
      const newAgent = randomUUID();
      const newRegistered = await target("POST", "/api/agents", {
        agentId: newAgent,
        body: { name: `later-new-worker-${ctx.nonce}`, role: "worker", status: "online" },
      });
      expectStatus(newRegistered, [200, 201], "register an agent on the later release");
      const newTask = await createTask(target, agentId, `after the upgrade ${word}`);
      const newMemory = await indexMemory(
        target,
        agentId,
        `new memory ${ctx.nonce}`,
        "violet heron canyon dolphin ember falcon",
      );
      const newSchedule = await target("POST", "/api/schedules", {
        body: {
          name: `later-new-schedule-${ctx.nonce}`,
          cronExpression: "0 0 1 1 *",
          taskTemplate: "later new schedule task",
          targetAgentId: newAgent,
        },
      });
      expectStatus(newSchedule, [200, 201], "create a schedule on the later release");
      const newConfig = await target("PUT", "/api/config", {
        body: { scope: "global", key: `${configKey}_NEW`, value: "new", isSecret: false },
      });
      expectStatus(newConfig, [200, 201], "write config on the later release");
      // A new row takes a key above every copied key of its table.
      for (const [table, id] of [
        ["agents", newAgent],
        ["agent_tasks", newTask],
        ["agent_memory", newMemory],
      ] as const) {
        const copiedMax = sourceDb.get<{ max: number }>(
          sql`SELECT COALESCE(max(rowid), 0) AS max FROM ${sqlIdent(table)}`,
        )?.max;
        const key = targetDb.get<{ key: number }>(
          sql`SELECT "_rowid"::int AS key FROM ${sqlIdent(table)} WHERE id = ${id}`,
        )?.key;
        expect(
          typeof key === "number" && typeof copiedMax === "number" && key > copiedMax,
          `${table}: the new row has key ${key}, the largest copied key is ${copiedMax}`,
        );
      }
      // Every identity sequence stands past its table, and past the SQLite AUTOINCREMENT
      // counter of its table (a counter stays above keys that were deleted).
      const counters = new Map(
        sourceDb
          .query<{ name: string; seq: number }>("SELECT name, seq FROM sqlite_sequence")
          .map((row) => [row.name, BigInt(row.seq)]),
      );
      const positions = sequences(targetDb);
      expect(positions.length > 100, `only ${positions.length} identity columns on the copy`);
      const behind = positions.filter(
        (row) =>
          BigInt(row.next) <= BigInt(row.max) ||
          (row.column !== "_rowid" && BigInt(row.next) <= (counters.get(row.table) ?? 0n)),
      );
      expect(
        behind.length === 0,
        `sequences that would give a key again: ${JSON.stringify(behind.slice(0, 10))}`,
      );

      ctx.log(
        `later release: ${legacy.length} SQLite migrations carried, seed tables [${later.seeded.join(", ")}], ` +
          `${positions.length} identity sequences, AUTOINCREMENT counters ${JSON.stringify([...counters].map(([name, seq]) => `${name}=${seq}`))}`,
      );

      await assertSearch(
        "on the later release",
        [...copiedTasks, preUpgradeTask, newTask],
        [copiedMemory, newMemory],
      );

      // --- The later release starts again (boot 3): nothing to apply, nothing reset.
      await restartTarget(laterEnv);
      assertEmptyBus();
      const thirdLog = await targetLog();
      expect(
        applying(thirdLog).length === 0 && !thirdLog.includes("[pg-migrations] WARNING"),
        `the second start of the later release applied [${applying(thirdLog).join(", ")}] or warned: ${thirdLog.slice(0, 1500)}`,
      );
      expect(
        JSON.stringify(history(targetDb)) === JSON.stringify(upgraded),
        "the second start of the later release changed the migration history",
      );
      assertSeedsHold("second start of the later release");
      expect(
        (await widgetTitle(target)) === editedTitle,
        "the second start of the later release reset the operator's edit",
      );
      const lastTask = await createTask(target, agentId, `after the second start ${word}`);
      await assertSearch(
        "after the second start",
        [...copiedTasks, preUpgradeTask, newTask, lastTask],
        [copiedMemory, newMemory],
      );
    } finally {
      await pair.stop();
      rmSync(later.dir, { recursive: true, force: true });
    }
  },
};
